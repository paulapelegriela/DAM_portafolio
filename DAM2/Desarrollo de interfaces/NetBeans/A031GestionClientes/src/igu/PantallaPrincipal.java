    //metodo para inicializar la tabla (tambien se puede hacer desde la parte de diseño)
    private void inicializarTabla(){
        DefaultTableModel dtm = new DefaultTableModel();
        //con este metodo creamos las cabeceras
        dtm.setColumnIdentifiers(new String[]{"Nombre", "Apellidos", "FechaAlta", "Provincia"});
        //ahora lo cargamos en nuestro jtable
        //jTableClientes.setModel(dtm);
        List<Cliente> listaClientes = ClasePrincipal.getListaClientes();
        
        //Filas
        for (Cliente cliente : listaClientes){
            dtm.addRow(cliente.toArrayString());
        }
        jTableClientes.setModel(dtm);
        
    }

